"""비영리단체 관련 계약서 6종 DOCX 자동 생성 스크립트"""
import os
from docx import Document
from docx.shared import Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT

OUT = "docx_contracts"
os.makedirs(OUT, exist_ok=True)

def setup(doc):
    s = doc.styles['Normal']
    s.font.name = 'Malgun Gothic'
    s.font.size = Pt(11)
    s.paragraph_format.space_after = Pt(6)
    s.paragraph_format.line_spacing = 1.5

def title(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    r.font.size = Pt(18)
    r.font.bold = True
    doc.add_paragraph()

def heading(doc, text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.bold = True
    r.font.size = Pt(12)

def art(doc, t, lines):
    heading(doc, t)
    for l in lines:
        doc.add_paragraph(l)

def sig(doc, parties):
    doc.add_paragraph()
    doc.add_paragraph("위 계약의 성립을 증명하기 위하여 본 서면 2통을 작성하고, 각 당사자가 서명 날인 후 각 1통씩 보관한다.")
    doc.add_paragraph()
    doc.add_paragraph("20    년    월    일")
    doc.add_paragraph()
    for p in parties:
        doc.add_paragraph(p)
        doc.add_paragraph("  주소:")
        doc.add_paragraph("  성명:                    (인)")
        doc.add_paragraph("  주민등록번호:")
        doc.add_paragraph("  연락처:")
        doc.add_paragraph()

def legal(doc, refs):
    doc.add_paragraph()
    p = doc.add_paragraph()
    r = p.add_run("【법적 근거】")
    r.font.bold = True
    r.font.size = Pt(10)
    r.font.color.rgb = RGBColor(0x66,0x66,0x66)
    for ref in refs:
        p2 = doc.add_paragraph(f"  {ref}")
        for run in p2.runs:
            run.font.size = Pt(9)
            run.font.color.rgb = RGBColor(0x88,0x88,0x88)


